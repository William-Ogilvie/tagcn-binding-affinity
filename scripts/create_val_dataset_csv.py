"""
create_val_dataset_csv.py
=========================

Splits a processed dataset CSV into training and validation sets.
Takes a random subset (default 10%) for validation and saves both sets to new files.
"""

import argparse
import pandas as pd
from pathlib import Path
import sys

# Get the absolute path of the current script
script_path = Path(__file__).resolve()

# Go up two levels to get the project root:
project_root = script_path.parent.parent

def parse_args():
    parser = argparse.ArgumentParser(
        description="Split a dataset CSV into training and validation sets."
    )
    parser.add_argument(
        "--input_csv", 
        type=str, 
        required=True, 
        help="Path to the full dataset CSV (generated by create_dataset_csv.py)."
    )
    parser.add_argument(
        "--val_csv", 
        type=str, 
        required=True, 
        help="Path to save the validation subset CSV."
    )
    parser.add_argument(
        "--train_csv", 
        type=str, 
        required=True, 
        help="Path to save the remaining training subset CSV."
    )
    parser.add_argument(
        "--split_ratio", 
        type=float, 
        default=0.1, 
        help="Fraction of data to use for validation (default: 0.1 for 10%%)."
    )
    parser.add_argument(
        "--seed", 
        type=int, 
        default=42, 
        help="Random seed for reproducibility."
    )
    return parser.parse_args()

def main():
    args = parse_args()
    
    input_path = project_root / Path(args.input_csv)
    val_path = project_root / Path(args.val_csv)
    train_path = project_root / Path(args.train_csv)

    
    if not input_path.exists():
        print(f"Error: Input CSV {input_path} not found.")
        sys.exit(1)
        
    print(f"Loading dataset from {input_path}...")
    df = pd.read_csv(input_path)
    total_len = len(df)
    print(f"Total samples: {total_len}")
    
    # Create validation set
    val_df = df.sample(frac=args.split_ratio, random_state=args.seed)
    
    # Create training set (drop validation rows)
    train_df = df.drop(val_df.index)
    
    # Reset indices
    val_df = val_df.reset_index(drop=True)
    train_df = train_df.reset_index(drop=True)
    
    print(f"Validation samples: {len(val_df)}")
    print(f"Training samples: {len(train_df)}")
    
    # --- Verification ---
    print("\n--- Verifying Split ---")
    
    # Check 1: Length consistency
    if len(val_df) + len(train_df) == total_len:
        print("SUCCESS: Lengths are consistent.")
    else:
        print(f"ERROR: Length mismatch! {len(val_df)} + {len(train_df)} != {total_len}")
        sys.exit(1)
        
    # Check 2: No overlap in unique_id
    if 'unique_id' in df.columns:
        val_ids = set(val_df['unique_id'])
        train_ids = set(train_df['unique_id'])
        
        overlap = val_ids.intersection(train_ids)
        
        if len(overlap) == 0:
            print("SUCCESS: No overlap in unique_id between sets.")
        else:
            print(f"ERROR: Found {len(overlap)} overlapping IDs!")
            sys.exit(1)
    else:
        print("WARNING: 'unique_id' column not found, skipping overlap check.")

    # --- Saving ---
    print("\n--- Saving Files ---")
    
    # Ensure directories exist
    val_path.parent.mkdir(parents=True, exist_ok=True)
    train_path.parent.mkdir(parents=True, exist_ok=True)
    
    val_df.to_csv(val_path, index=False)
    print(f"Saved validation set to: {val_path}")
    
    train_df.to_csv(train_path, index=False)
    print(f"Saved training set to: {train_path}")

if __name__ == "__main__":
    main()
